interface TableViewProps {
  caption: string
  columns: string[]
  rows: (string | number)[][]
}

/** Screen-reader equivalent of a chart (identity and values never depend on colour). */
export function TableView({ caption, columns, rows }: TableViewProps) {
  return (
    <table className="sr-only">
      <caption>{caption}</caption>
      <thead>
        <tr>
          {columns.map((c) => (
            <th key={c} scope="col">
              {c}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((row, i) => (
          <tr key={i}>
            {row.map((cell, j) => (
              <td key={j}>{cell}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  )
}
